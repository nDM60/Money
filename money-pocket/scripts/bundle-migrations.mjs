#!/usr/bin/env node
// Embeds ./drizzle migrations into src/server/db/migrations.generated.ts so the
// server never has to read migration files from disk (serverless bundles don't
// keep the folder at a predictable path). Run after `drizzle-kit generate`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "drizzle");
const journal = JSON.parse(fs.readFileSync(path.join(dir, "meta", "_journal.json"), "utf8"));
const entries = journal.entries.map((e) => ({
  tag: e.tag,
  when: e.when,
  breakpoints: e.breakpoints,
  sql: fs.readFileSync(path.join(dir, `${e.tag}.sql`), "utf8"),
}));
const out = `// Generated by scripts/bundle-migrations.mjs from ./drizzle — do not edit.
export const MIGRATIONS: { tag: string; when: number; breakpoints: boolean; sql: string }[] = ${JSON.stringify(entries, null, 2)};
`;
const target = path.join(root, "src", "server", "db", "migrations.generated.ts");
if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) {
  fs.writeFileSync(target, out);
  console.log(`bundled ${entries.length} migration(s) into ${path.relative(root, target)}`);
}
